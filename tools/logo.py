#!/usr/bin/env python3
"""Primer's logo and the Kindle launcher that carries it.

Draws the wordmark "primer" (Inter Bold) over a swoosh in the spirit of Amazon's smile, but
where Amazon's arrow points from a to z, Primer's curve ends in a folded page corner: a page
being turned. Black on white, for e-ink.

Writes design/primer-wordmark.png (the logo alone, for the README), design/primer-logo.png
(the Kindle cover, 938x1432, like a scriptlet's own) and
src/scriptlets/Primer.sh, the KPM scriptlet that shows on a jailbroken Kindle's home screen
as "Primer" with that cover and starts KOReader. Run from anywhere: python3 tools/logo.py
"""
import base64, io, os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT = os.path.join(ROOT, "src/fonts/Inter-Bold.ttf")
W, H = 938, 1432          # a Kindle cover, same as KOReader's scriptlet icon
SCALE = 4                 # draw big, downsample for smooth edges

def bezier(p0, p1, p2, n=200):
    return [((1-t)**2*p0[0] + 2*(1-t)*t*p1[0] + t**2*p2[0],
             (1-t)**2*p0[1] + 2*(1-t)*t*p1[1] + t**2*p2[1]) for t in (i/n for i in range(n+1))]

def draw_logo(size, word_px, pad):
    """The wordmark and swoosh on a transparent canvas of `size`, word in `word_px` pixels."""
    w, h = size
    img = Image.new("L", (w*SCALE, h*SCALE), 255)
    d = ImageDraw.Draw(img)
    font = ImageFont.truetype(FONT, word_px*SCALE)
    text = "primer"
    bbox = d.textbbox((0, 0), text, font=font)
    tw, th = bbox[2]-bbox[0], bbox[3]-bbox[1]
    tx = (w*SCALE - tw)//2 - bbox[0]
    ty = (h*SCALE - th)//2 - bbox[1] - int(0.35*word_px*SCALE)
    d.text((tx, ty), text, font=font, fill=0)
    # The swoosh: from under the p's stem to under the r, sagging like the smile and rising at
    # the end, drawn as a trail of discs so the stroke has no seams.
    base = ty + bbox[3] + int(0.12*word_px*SCALE)      # just under the x-height letters
    x0 = tx + bbox[0] + int(0.08*tw)
    x1 = tx + bbox[0] + int(0.86*tw)
    sag = int(0.42*word_px*SCALE)
    stroke = max(2, int(0.085*word_px*SCALE))
    pts = bezier((x0, base), ((x0+x1)//2, base + 2*sag), (x1, base + int(0.55*sag)), n=600)
    r = stroke/2
    for x, y in pts:
        d.ellipse((x-r, y-r, x+r, y+r), fill=0)
    # Where Amazon's arrowhead would be, a folded page corner: a solid right triangle whose
    # hypotenuse carries on the curve's rise, with a fold line inset from the hypotenuse.
    ex, ey = pts[-1]
    s = int(0.34*word_px*SCALE)
    a = (ex - r, ey + r)            # bottom-left, on the curve's end
    b = (ex - r + s, ey + r)        # bottom-right
    c = (ex - r + s, ey + r - s)    # top-right
    d.polygon([a, b, c], fill=0)
    inset = stroke*1.4
    d.line([(a[0] + 2.2*inset, a[1] - inset), (c[0] - inset, c[1] + 2.2*inset)], fill=255, width=int(stroke*0.55))
    return img.resize((w, h), Image.LANCZOS)

def cover():
    img = draw_logo((W, H), 150, 0)
    d = ImageDraw.Draw(img)
    # A thin frame, like a book cover's edge.
    d.rectangle((0, 0, W-1, H-1), outline=0, width=6)
    return img

def wordmark():
    """The logo cropped to its ink with a margin, on white (so it reads on GitHub's dark theme too)."""
    img = draw_logo((1400, 700), 220, 0)
    box = Image.eval(img, lambda v: 255 - v).getbbox()
    pad = 60
    return img.crop((box[0] - pad, box[1] - pad, box[2] + pad, box[3] + pad))

if __name__ == "__main__":
    wordmark().save(os.path.join(ROOT, "design/primer-wordmark.png"), optimize=True)
    cov = cover()
    cov.save(os.path.join(ROOT, "design/primer-logo.png"), optimize=True)
    buf = io.BytesIO(); cov.save(buf, "PNG", optimize=True)
    icon = base64.b64encode(buf.getvalue()).decode()
    script = f"""#!/bin/sh
# Name: Primer
# Author: skuthus
# Icon: data:image/png;base64,{icon}
# DontUseFBInk
# Primer's launcher for Kindles on the hdnext stack (firmware 5.16.3+, jailbroken with KPM):
# shows on the home screen as "Primer" with the cover above, and starts KOReader (with Primer
# inside). Generated by tools/logo.py.

/var/local/kmc/bin/kpm launch koreader --asap
"""
    with open(os.path.join(ROOT, "src/scriptlets/Primer.sh"), "w") as f:
        f.write(script)
    print("wrote design/primer-wordmark.png, design/primer-logo.png and src/scriptlets/Primer.sh", len(icon)//1024, "KB icon")
